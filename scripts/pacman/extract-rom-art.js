// @ts-check
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

// Turns the graphics ROMs and the color PROMs of Pac-Man into readable TypeScript:
//   games/pacman/src/art/sprites-XX.ts   8 sprites of 16x16 pixels each, as "ASCII art"
//   games/pacman/src/art/chars-XX.ts     32 characters of 8x8 pixels each, as "ASCII art"
//   games/pacman/src/art/color-proms.ts  the two color PROMs, byte by byte
// Every pixel is one of four values, written ".", "1", "2", "3": "." is transparent.
// The ROMs are not part of the repository (they are Namco's): pass the folder holding them,
// named as in the MAME "pacman" set (pacman.5e, pacman.5f, 82s123.7f, 82s126.4a).
//   node scripts/pacman/extract-rom-art.js path/to/roms
// The tile layout is the one of Galaga, its younger sibling: see scripts/galaga/extract-rom-art.js.

const romDir = process.argv[2];
if (!romDir) {
  process.stderr.write(
    'Usage: node scripts/pacman/extract-rom-art.js <folder with the Pac-Man ROMs>\n',
  );
  process.exit(1);
}
const OUT = join(import.meta.dirname, '..', '..', 'games', 'pacman', 'src', 'art');
const read = (/** @type {string} */ name) => readFileSync(join(romDir, name));

/**
 * Bit `offset` of a graphics tile that starts at byte `base`, most significant bit first.
 * @param {Buffer} data @param {number} base @param {number} offset
 */
const bit = (data, base, offset) => (data[base + (offset >> 3)] >> (7 - (offset & 7))) & 1;

/**
 * Decodes one tile into rows of pixel values, already turned the way the vertical monitor
 * shows it. The Namco hardware stores 2 bits per pixel in two "planes" 4 bits apart, and draws
 * the tile on a monitor lying on its side: the stored column u becomes screen row u, the stored
 * row v becomes screen column (size - 1 - v). The offsets are the ones of the MAME gfx layout.
 * @param {Buffer} data @param {number} base @param {number[]} xOffsets @param {number[]} yOffsets
 */
const decodeTile = (data, base, xOffsets, yOffsets) => {
  const size = xOffsets.length;
  return xOffsets.map((xOffset) =>
    Array.from({ length: size }, (_, column) => {
      const offset = xOffset + yOffsets[size - 1 - column];
      return '.123'[(bit(data, base, offset) << 1) | bit(data, base, offset + 4)];
    }).join(''),
  );
};

// Unlike Galaga, the first 4 columns of a Pac-Man sprite are stored last.
const SPRITE_X = [64, 65, 66, 67, 128, 129, 130, 131, 192, 193, 194, 195, 0, 1, 2, 3];
const SPRITE_Y = [0, 8, 16, 24, 32, 40, 48, 56, 256, 264, 272, 280, 288, 296, 304, 312];
const CHAR_X = [64, 65, 66, 67, 0, 1, 2, 3];
const CHAR_Y = [0, 8, 16, 24, 32, 40, 48, 56];

const hex = (/** @type {number} */ n) => n.toString(16).toUpperCase().padStart(2, '0');

/**
 * The source of one generated file: a list of tiles, each with its code as a comment.
 * @param {string} name @param {string} doc @param {number} first @param {string[][]} tiles
 */
const artFile = (name, doc, first, tiles) =>
  [
    '// Generated by scripts/pacman/extract-rom-art.js from the Pac-Man ROMs: do not edit.',
    "import type { ArtRows } from '@arcade/tiles';",
    '',
    `/** ${doc} */`,
    `export const ${name}: readonly ArtRows[] = [`,
    ...tiles.flatMap((rows, index) => [
      `  // 0x${hex(first + index)}`,
      '  [',
      ...rows.map((row) => `    '${row}',`),
      '  ],',
    ]),
    '];',
    '',
  ].join('\n');

mkdirSync(OUT, { recursive: true });

const sprites = read('pacman.5f');
for (let first = 0; first < 64; first += 8) {
  const tiles = Array.from({ length: 8 }, (_, i) =>
    decodeTile(sprites, (first + i) * 64, SPRITE_X, SPRITE_Y),
  );
  const name = `sprites${hex(first)}`;
  const doc = `Sprites 0x${hex(first)}-0x${hex(first + 7)} of the sprite ROM (5f).`;
  writeFileSync(
    join(OUT, `sprites-${hex(first).toLowerCase()}.ts`),
    artFile(name, doc, first, tiles),
  );
}

const chars = read('pacman.5e');
for (let first = 0; first < 256; first += 32) {
  const tiles = Array.from({ length: 32 }, (_, i) =>
    decodeTile(chars, (first + i) * 16, CHAR_X, CHAR_Y),
  );
  const name = `chars${hex(first)}`;
  const doc = `Characters 0x${hex(first)}-0x${hex(first + 31)} of the character ROM (5e).`;
  writeFileSync(
    join(OUT, `chars-${hex(first).toLowerCase()}.ts`),
    artFile(name, doc, first, tiles),
  );
}

/**
 * A PROM as a TypeScript array of bytes, 16 per line.
 * @param {string} name @param {string} doc @param {Buffer} bytes
 */
const promSource = (name, doc, bytes) => {
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push(
      `  ${[...bytes.subarray(i, i + 16)].map((b) => `0x${hex(b).toLowerCase()}`).join(', ')},`,
    );
  }
  return [`/** ${doc} */`, `export const ${name}: readonly number[] = [`, ...lines, '];', ''].join(
    '\n',
  );
};

writeFileSync(
  join(OUT, 'color-proms.ts'),
  [
    '// Generated by scripts/pacman/extract-rom-art.js from the Pac-Man PROMs: do not edit.',
    '',
    promSource(
      'PALETTE_PROM',
      'PROM 7f: the colors of the screen, one byte each as BBGGGRRR. Only the first 16 are used.',
      read('82s123.7f'),
    ),
    promSource(
      'LOOKUP_PROM',
      'PROM 4a: for each of the 64 palettes, the 4 colors (0-15) of its pixel values 0-3. Characters and sprites share it.',
      read('82s126.4a'),
    ),
  ].join('\n'),
);
