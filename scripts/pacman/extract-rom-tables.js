// @ts-check
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Buffer } from 'node:buffer';
import process from 'node:process';

// Copies the data tables of the Pac-Man program (pacman.6e-6j in the MAME "pacman" set) into
//   games/pacman/src/rom/main-rom.ts     the byte tables, each with its ROM address
//   games/pacman/src/rom/texts.ts        the 55 messages of the text routine at $2C5E
//   games/pacman/src/rom/random-bits.ts  the low 2 bits of $0000-$1FFF, read by the random routine
//   node scripts/pacman/extract-rom-tables.js path/to/roms

const romDir = process.argv[2];
if (!romDir) {
  process.stderr.write('Usage: node scripts/pacman/extract-rom-tables.js <folder with the ROMs>\n');
  process.exit(1);
}
const OUT = join(import.meta.dirname, '..', '..', 'games', 'pacman', 'src', 'rom');
const rom = Buffer.concat(
  ['pacman.6e', 'pacman.6f', 'pacman.6h', 'pacman.6j'].map((name) =>
    readFileSync(join(romDir, name)),
  ),
);

/** The tables: name in the remake, what the program uses it for, address and length in bytes. */
const TABLES = [
  { name: 'DIFFICULTY', doc: '6 bytes per level, 21 levels', address: 0x0796, length: 126 },
  { name: 'HOUSE_DOT_LIMITS', doc: 'dots for Pinky, Inky, Clyde', address: 0x0843, length: 12 },
  { name: 'ELROY_DOTS', doc: 'dots left for Elroy 1 and 2', address: 0x084f, length: 18 },
  { name: 'FRIGHT_TIMES', doc: 'blue time, words', address: 0x0861, length: 18 },
  { name: 'HOUSE_TIMERS', doc: 'frames without dots, words', address: 0x0873, length: 6 },
  { name: 'FRUITS', doc: 'sprite, color, score per level', address: 0x0efd, length: 63 },
  { name: 'EXTRA_LIFE', doc: 'thousands, BCD, per DIP switch', address: 0x2728, length: 4 },
  { name: 'DIRECTION_STEPS', doc: 'Y, X step per direction', address: 0x32ff, length: 8 },
  { name: 'SPEEDS', doc: '42 bytes per speed entry', address: 0x330f, length: 7 * 42 },
  { name: 'MAZE_DRAWING', doc: 'compressed maze tiles', address: 0x3435, length: 381 },
  { name: 'DOT_STEPS', doc: 'distance between dot cells', address: 0x35b5, length: 240 },
];

const hex = (/** @type {number} */ n, /** @type {number} */ digits) =>
  n.toString(16).padStart(digits, '0');

/**
 * Bytes as source lines, 16 per line, each line with its address.
 * @param {number} address @param {number} length
 */
const byteLines = (address, length) => {
  const lines = [];
  for (let offset = 0; offset < length; offset += 16) {
    const bytes = [...rom.subarray(address + offset, address + Math.min(offset + 16, length))];
    lines.push(
      `  /* ${hex(address + offset, 4)} */ ${bytes.map((b) => `0x${hex(b, 2)}`).join(', ')},`,
    );
  }
  return lines;
};

/** @param {{ name: string; doc: string; address: number; length: number }} table */
const tableSource = ({ name, doc, address, length }) => [
  `/** $${hex(address, 4)}: ${doc}. */`,
  `export const ${name}: readonly number[] = [`,
  ...byteLines(address, length),
  '];',
  '',
];

mkdirSync(OUT, { recursive: true });
writeFileSync(
  join(OUT, 'main-rom.ts'),
  [
    '// Generated by scripts/pacman/extract-rom-tables.js from the Pac-Man ROMs: do not edit.',
    '',
    ...TABLES.flatMap(tableSource),
  ].join('\n'),
);

// The text routine at $2C5E reads a pointer from $36A5, then: a 2-byte video offset (bit 15 set
// means the message runs along the score rows, where the next cell is 1 byte away instead of 32),
// the tile codes up to the end mark $2F, then either one color with bit 7 set for the whole
// message or one color per tile. Pointers below $0100 are unused slots.
const TEXT_POINTERS = 0x36a5;
const TEXT_COUNT = 55;
const END_MARK = 0x2f;

/** @param {number} at */
const word = (at) => rom[at] | (rom[at + 1] << 8);

/** @param {number} index */
const textSource = (index) => {
  const at = word(TEXT_POINTERS + index * 2);
  if (at < 0x100)
    return `  // ${index}: unused\n  { offset: 0, alongRow: false, tiles: [], colors: [] },`;
  const offset = word(at);
  const tiles = [];
  let cursor = at + 2;
  for (; rom[cursor] !== END_MARK; cursor += 1) tiles.push(rom[cursor]);
  cursor += 1;
  const colors =
    rom[cursor] & 0x80 ? tiles.map(() => rom[cursor] & 0x7f) : tiles.map((_, i) => rom[cursor + i]);
  const shown = tiles.map((t) => (t >= 0x41 && t <= 0x5a ? String.fromCharCode(t) : '·')).join('');
  return [
    `  // ${index}: ${shown} ($${hex(at, 4)})`,
    `  {`,
    `    offset: 0x${hex(offset & 0x3ff, 3)},`,
    `    alongRow: ${(offset & 0x8000) !== 0},`,
    `    tiles: [${tiles.map((t) => `0x${hex(t, 2)}`).join(', ')}],`,
    `    colors: [${colors.map((c) => `0x${hex(c, 2)}`).join(', ')}],`,
    '  },',
  ].join('\n');
};

writeFileSync(
  join(OUT, 'texts.ts'),
  [
    '// Generated by scripts/pacman/extract-rom-tables.js from the Pac-Man ROMs: do not edit.',
    "import type { RomText } from '../texts';",
    '',
    '/** The messages of the text routine at $2C5E, by number (pointer table at $36A5). */',
    'export const ROM_TEXTS: readonly RomText[] = [',
    ...Array.from({ length: TEXT_COUNT }, (_, i) => textSource(i)),
    '];',
    '',
  ].join('\n'),
);

// The random routine at $2A23 returns the program byte at a pseudo-random address in
// $0000-$1FFF and the ghosts keep only its 2 low bits: 4 of them are packed in each byte here.
const RANDOM_SPAN = 0x2000;
const packed = Buffer.from(
  Array.from({ length: RANDOM_SPAN / 4 }, (_, i) =>
    [0, 1, 2, 3].reduce((byte, k) => byte | ((rom[i * 4 + k] & 3) << (k * 2)), 0),
  ),
);
const packedLines = [];
for (let offset = 0; offset < packed.length; offset += 16) {
  packedLines.push(
    `  ${[...packed.subarray(offset, offset + 16)].map((b) => `0x${hex(b, 2)}`).join(', ')},`,
  );
}
writeFileSync(
  join(OUT, 'random-bits.ts'),
  [
    '// Generated by scripts/pacman/extract-rom-tables.js from the Pac-Man ROMs: do not edit.',
    '',
    '/** The 2 low bits of each program byte $0000-$1FFF, 4 per byte, the first in bits 0-1. */',
    'export const RANDOM_BITS: readonly number[] = [',
    ...packedLines,
    '];',
    '',
  ].join('\n'),
);
