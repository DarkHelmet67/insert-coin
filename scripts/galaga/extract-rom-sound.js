// @ts-check
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

// Copies the data of Galaga's sound processor (3700g.bin: note table, effect tables and
// melodies) and the waveform PROM of the sound chip (prom-1.1d) into
//   games/galaga/src/rom/sound-rom.ts
// The commented source of the sound program (gg1-7.s) was written on the Namco set, where the
// same bytes sit $27 bytes lower: its labels are given with both addresses.
//   node scripts/galaga/extract-rom-sound.js path/to/roms

const romDir = process.argv[2];
if (!romDir) {
  process.stderr.write('Usage: node scripts/galaga/extract-rom-sound.js <folder with the ROMs>\n');
  process.exit(1);
}
const OUT = join(import.meta.dirname, '..', '..', 'games', 'galaga', 'src', 'rom', 'sound-rom.ts');
const program = readFileSync(join(romDir, '3700g.bin'));
const prom = readFileSync(join(romDir, 'prom-1.1d'));

/** First and last byte of the data in the sound ROM: the note table up to the last melody. */
const FIRST = 0x06d0;
const LAST = 0x0f55;

const hex = (/** @type {number} */ n, /** @type {number} */ digits) =>
  n.toString(16).padStart(digits, '0');

/**
 * Bytes as source lines of 16, each with its address.
 * @param {Uint8Array} bytes
 * @param {number} address
 */
const lines = (bytes, address) => {
  const out = [];
  for (let offset = 0; offset < bytes.length; offset += 16) {
    const row = [...bytes.subarray(offset, offset + 16)].map((b) => `0x${hex(b, 2)}`);
    out.push(`  /* ${hex(address + offset, 4)} */ ${row.join(', ')},`);
  }
  return out;
};

writeFileSync(
  OUT,
  [
    '// Generated by scripts/galaga/extract-rom-sound.js from the Galaga ROMs: do not edit.',
    '',
    `/** Address of the first byte of \`SOUND_DATA\` in the sound processor's ROM. */`,
    `export const SOUND_DATA_ADDRESS = 0x${hex(FIRST, 4)};`,
    '',
    '/**',
    ' * The data of the sound program, from `d_06A9_ndat` (the note table) to the end of the last',
    ' * melody.',
    ' */',
    'export const SOUND_DATA: readonly number[] = [',
    ...lines(program.subarray(FIRST, LAST + 1), FIRST),
    '];',
    '',
    '/** The waveform PROM of the sound chip: 8 waveforms of 32 samples of 4 bits. */',
    'export const WAVEFORM_PROM: readonly number[] = [',
    ...lines(prom, 0),
    '];',
    '',
  ].join('\n'),
);
