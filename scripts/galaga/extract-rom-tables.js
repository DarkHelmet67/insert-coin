// @ts-check
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Buffer } from 'node:buffer';
import process from 'node:process';

// Copies the data tables of Galaga's main processor (3200a-3500d.bin in the MAME "galagamw" set)
// into
//   games/galaga/src/rom/main-rom.ts
// Each table keeps the label it has in the commented source of the program, and its address in
// this ROM set (a few bytes away from the Namco set the source was written on: the bytes are the
// same, the code around them moved).
//   node scripts/galaga/extract-rom-tables.js path/to/roms

const romDir = process.argv[2];
if (!romDir) {
  process.stderr.write('Usage: node scripts/galaga/extract-rom-tables.js <folder with the ROMs>\n');
  process.exit(1);
}
const OUT = join(import.meta.dirname, '..', '..', 'games', 'galaga', 'src', 'rom');
const rom = Buffer.concat(
  ['3200a.bin', '3300b.bin', '3400c.bin', '3500d.bin'].map((name) =>
    readFileSync(join(romDir, name)),
  ),
);

/** The tables: name in the remake, label in the source, address and length in bytes. */
const TABLES = [
  { name: 'SCORE_STEPS', label: 'd_scoreman_inc_lut', address: 0x080e, length: 16 },
  { name: 'RED_BOMBER_TIMERS', label: 'd_08CD', address: 0x08e0, length: 30 },
  { name: 'YELLOW_BOMBER_TIMERS', label: 'd_08EB', address: 0x08fe, length: 30 },
  { name: 'BOMB_ENABLE_TABLE', label: 'd_0909, d_0929', address: 0x091c, length: 44 },
  { name: 'BREATHING_BITMAPS', label: 'd_1E64_bitmap_tables', address: 0x1e6a, length: 64 },
  { name: 'COMBAT_STAGE_INDEX', label: 'd_combat_stg_dat_idx', address: 0x26b6, length: 68 },
  { name: 'CHALLENGE_STAGE_INDEX', label: 'd_challg_stg_data_idx', address: 0x26fa, length: 8 },
  { name: 'COMBAT_STAGES', label: 'd_combat_stg_dat', address: 0x2702, length: 234 },
  { name: 'CHALLENGE_STAGES', label: 'd_challg_stg_dat', address: 0x27ec, length: 144 },
  { name: 'WAVE_OBJECTS', label: 'db_attk_wav_IDs', address: 0x287c, length: 40 },
  { name: 'CHALLENGE_BONUS', label: 'd_stage_chllg_rnd_attrib', address: 0x290e, length: 8 },
  { name: 'BOMBER_BITS', label: 'd_2908', address: 0x2916, length: 6 },
  { name: 'CHALLENGE_LOOKS', label: 'd_290E', address: 0x291c, length: 8 },
  { name: 'ENTRY_PROGRAMS', label: 'db_2A3C', address: 0x2a4a, length: 48 },
  { name: 'ENTRY_STARTS', label: 'db_2A6C', address: 0x2a7a, length: 36 },
  { name: 'STAGE_PARAMETERS', label: 'bmbr_stg_cfg_dat', address: 0x2c6d, length: 520 },
];

const hex = (/** @type {number} */ n, /** @type {number} */ digits) =>
  n.toString(16).padStart(digits, '0');

/**
 * One table as source: 16 bytes per line, each line with its address.
 * @param {{ name: string; label: string; address: number; length: number }} table
 */
const tableSource = ({ name, label, address, length }) => {
  const lines = [];
  for (let offset = 0; offset < length; offset += 16) {
    const bytes = [...rom.subarray(address + offset, address + Math.min(offset + 16, length))];
    lines.push(
      `  /* ${hex(address + offset, 4)} */ ${bytes.map((b) => `0x${hex(b, 2)}`).join(', ')},`,
    );
  }
  return [
    `/** \`${label}\` at $${hex(address, 4)}. */`,
    `export const ${name}: readonly number[] = [`,
    ...lines,
    '];',
    '',
  ];
};

mkdirSync(OUT, { recursive: true });
writeFileSync(
  join(OUT, 'main-rom.ts'),
  [
    '// Generated by scripts/galaga/extract-rom-tables.js from the Galaga ROMs: do not edit.',
    '',
    ...TABLES.flatMap(tableSource),
  ].join('\n'),
);
