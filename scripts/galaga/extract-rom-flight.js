// @ts-check
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

// Copies the flight programs of the aliens out of the ROM of Galaga's second processor
// (3600e.bin in the MAME "galagamw" set, the same bytes as gg1-5 of the Namco set) into
//   games/galaga/src/rom/flight-rom.ts
// Only the data areas are copied, at their original addresses: the programs jump to each other
// by address, so the remake reads them exactly where the original does.
//   node scripts/galaga/extract-rom-flight.js path/to/roms

const romDir = process.argv[2];
if (!romDir) {
  process.stderr.write('Usage: node scripts/galaga/extract-rom-flight.js <folder with the ROMs>\n');
  process.exit(1);
}
const OUT = join(import.meta.dirname, '..', '..', 'games', 'galaga', 'src', 'rom');
const rom = readFileSync(join(romDir, '3600e.bin'));

/** The data areas of the ROM, [first, end) with the labels of the commented source. */
const AREAS = [
  { first: 0x001d, end: 0x0034, labels: 'db_flv_001d' },
  { first: 0x004b, end: 0x0513, labels: 'p_flv_004b ... db_flv_0502 (sprt_fmtn_hpos included)' },
  { first: 0x0fda, end: 0x0ffd, labels: 'db_flv_0fda, db_flv_0ff0' },
];

const hex = (/** @type {number} */ n, /** @type {number} */ digits) =>
  n.toString(16).padStart(digits, '0');

/**
 * One area as source: 16 bytes per line, each line with its address.
 * @param {{ first: number; end: number; labels: string }} area
 */
const areaSource = ({ first, end, labels }) => {
  const lines = [];
  for (let address = first; address < end; address += 16) {
    const bytes = [...rom.subarray(address, Math.min(address + 16, end))];
    lines.push(`      /* ${hex(address, 4)} */ ${bytes.map((b) => `0x${hex(b, 2)}`).join(', ')},`);
  }
  return [
    '  {',
    `    // ${labels}`,
    `    address: 0x${hex(first, 4)},`,
    '    bytes: [',
    ...lines,
    '    ],',
    '  },',
  ];
};

mkdirSync(OUT, { recursive: true });
writeFileSync(
  join(OUT, 'flight-rom.ts'),
  [
    '// Generated by scripts/galaga/extract-rom-flight.js from the Galaga ROMs: do not edit.',
    '',
    '/** A run of bytes of the second processor ROM, starting at `address`. */',
    'export interface RomArea {',
    '  readonly address: number;',
    '  readonly bytes: readonly number[];',
    '}',
    '',
    '/** The data areas of the second processor ROM: flight programs and the formation layout. */',
    'export const FLIGHT_ROM: readonly RomArea[] = [',
    ...AREAS.flatMap(areaSource),
    '];',
    '',
  ].join('\n'),
);
